// Local browser regression check. Desktop SQLite and installer upgrade are tested separately on Windows.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.APP_URL || 'http://localhost:1420');
  const legacy = Array.from({ length: 3 }, (_, i) => ({ id: `old-${i}`, title: `Departamento original ${i+1}`, url: '', rent: 500000+i*100000, expenses: 80000, area: 52, metro: 'Chile España', distance: 350, floor: 7, terrace: 4, finishes: 5, parking: 1, phone: '+56 9 1234 5678', contacted: i===0, visited: false, notes: `Nota original ${i+1}`, createdAt: `2026-10-0${i+1}` }));
  const raw = JSON.stringify(legacy);
  await page.evaluate(raw => {localStorage.clear();localStorage.setItem('arriendos.preview.v1', raw);}, raw);
  await page.reload();
  await page.getByRole('heading', { name: 'Departamento original 1', exact: true }).waitFor();
  assert.equal(await page.locator('tbody tr').count(), 3);
  assert.equal(await page.locator('article').count(), 0);
  assert.equal(await page.evaluate(() => localStorage.getItem('arriendos.preview.v1')), raw, 'Leer no debe reescribir datos antiguos');
  await page.getByRole('button', { name: 'Editar Departamento original 1' }).click();
  await page.getByLabel('ID de publicación', { exact: true }).fill('NUN-001');
  await page.getByLabel('Disponibilidad', { exact: true }).selectOption('paused');
  await page.getByRole('checkbox', { name: 'Visita agendada', exact: true }).check();
  await page.getByRole('button', { name: 'Guardar departamento', exact: true }).click();
  assert.ok(await page.getByRole('dialog').isVisible(), 'La agenda requiere una fecha y hora');
  await page.getByLabel('Fecha y hora de visita', { exact: true }).fill('2030-06-15T11:30');
  await page.getByRole('button', { name: 'Guardar departamento', exact: true }).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByLabel('Buscar departamento').fill('nun-001');
  assert.equal(await page.locator('tbody tr').count(), 1);
  await page.getByLabel('Filtrar por disponibilidad').selectOption('paused');
  await page.getByLabel('Disponibilidad de Departamento original 1', { exact: true }).selectOption('finished');
  await page.getByRole('heading', { name: 'No hay coincidencias' }).waitFor();
  await page.getByLabel('Filtrar por disponibilidad').selectOption('finished');
  await page.getByRole('heading', { name: 'Departamento original 1', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Columnas', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Notas', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Superficie', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  assert.equal(await page.getByRole('columnheader', { name: 'Superficie', exact: true }).count(), 0);
  await page.reload();
  await page.getByText('ID: NUN-001', { exact: true }).waitFor();
  await page.getByText('Nota original 1', { exact: true }).waitFor();
  assert.equal(await page.getByRole('columnheader', { name: 'Superficie', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Agendadas', exact: true }).click();
  assert.equal(await page.locator('tbody tr').count(), 1);
  assert.equal(await page.locator('time').getAttribute('datetime'), '2030-06-15T11:30');
  await page.getByRole('button', { name: 'Editar Departamento original 1' }).click();
  await page.getByRole('checkbox', { name: 'Visita agendada', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Guardar departamento', exact: true }).click();
  await page.getByRole('heading', { name: 'No hay coincidencias' }).waitFor();
  await page.getByRole('button', { name: 'Limpiar filtros' }).click();
  assert.equal(await page.locator('tbody tr').count(), 3);
  await page.screenshot({ path: '/tmp/arriendos-0.2.0.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'La tabla debe desplazarse dentro del listado');
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('arriendos.preview.v1')));
  for (const old of legacy.slice(1)) assert.deepEqual(Object.fromEntries(Object.keys(old).map(k => [k,saved.find(a=>a.id===old.id)[k]])),old);
  assert.deepEqual(errors, []);
  console.log('PASS: 3 registros antiguos, lista, ID, disponibilidad, agenda obligatoria/cancelación, filtros, columnas persistentes y ancho móvil');
} finally { await browser.close(); }
